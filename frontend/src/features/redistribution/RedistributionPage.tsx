import { useState } from 'react';
import { ArrowRight, CalendarClock, Info, Route, Send, TriangleAlert } from 'lucide-react';
import type { Recommendation, RecommendationReason } from '@/api/types';
import { useCurrentUser } from '@/auth/AuthContext';
import { useFacilityScope } from '@/auth/FacilityScope';
import { can } from '@/auth/permissions';
import { Badge, Button, Card, EmptyState, ErrorState, FilterSelect, PageHeader, Pagination, SearchInput, Skeleton, Toolbar } from '@/components/ui';
import { useRecommendations } from '@/hooks/queries';
import { useListParams } from '@/hooks/useListParams';
import { daysUntil, fmtDate, fmtNumber } from '@/lib/format';
import { REASON_LABEL } from '@/lib/labels';
import { cn } from '@/lib/utils';
import { RequestTransferModal, type TransferPrefill } from '../transfers/RequestTransferModal';

const FILTERS = ['reason'] as const;
const SORTS = [
  { value: 'priorityScore:desc', label: 'Highest priority' },
  { value: 'distanceKm:asc', label: 'Shortest distance' },
  { value: 'expiryDate:asc', label: 'Earliest expiry' },
  { value: 'suggestedQuantity:desc', label: 'Largest quantity' },
];

function PriorityPill({ score }: { score: number }) {
  const tone = score >= 70 ? 'bg-danger-50 text-danger-700 ring-danger-100' : score >= 45 ? 'bg-warning-50 text-warning-700 ring-warning-100' : 'bg-subtle text-ink-700 ring-line';
  const label = score >= 70 ? 'High' : score >= 45 ? 'Medium' : 'Low';
  return (
    <span className={cn('tabular inline-flex items-center gap-1 rounded-md px-2 py-1 text-xs font-semibold ring-1 ring-inset', tone)} title="Priority score (0–100) combining shortage severity, expiry urgency and distance">
      {score}
      <span className="font-medium">{label}</span>
    </span>
  );
}

export default function RedistributionPage() {
  const user = useCurrentUser();
  const scope = useFacilityScope();
  const lp = useListParams(FILTERS, { sortBy: 'priorityScore', sortDir: 'desc', pageSize: 10 });
  const q = useRecommendations({ ...lp.query, facilityId: scope.facilityId, reasonCode: lp.filters.reason as RecommendationReason | undefined });
  const [transfer, setTransfer] = useState<TransferPrefill | null>(null);

  const accept = (r: Recommendation) =>
    setTransfer({
      medicine: r.medicine,
      batch: { id: r.batch.id, batchNumber: r.batch.batchNumber, quantityAvailable: r.batch.quantityAvailable, expiryDate: r.expiryDate, facility: r.sourceFacility },
      destinationFacilityId: r.destinationFacility.id,
      quantity: r.suggestedQuantity,
      recommendationId: r.id,
      reason: r.reason,
    });

  return (
    <>
      <PageHeader
        title="Redistribution recommendations"
        description="Suggested inter-facility moves that cover shortages or rescue near-expiry stock. Requesting a transfer reserves the units at the source."
      />
      <div className="mb-4 flex items-start gap-2 rounded-lg border border-info-100 bg-info-50 px-4 py-3 text-xs text-info-700">
        <Info className="mt-px size-4 shrink-0" />
        <p>
          Recommendations are generated by the MedShare redistribution engine from current stock, 30-day consumption and facility distances. They are advisory — the source facility
          still approves every transfer.
        </p>
      </div>
      <Card>
        <Toolbar onClear={lp.clearFilters} showClear={lp.hasActiveFilters}>
          <SearchInput value={lp.search} onChange={lp.setSearch} placeholder="Search medicine or facility…" />
          <FilterSelect
            label="Reason"
            value={lp.filters.reason}
            onChange={(v) => lp.setFilter('reason', v)}
            options={(Object.keys(REASON_LABEL) as RecommendationReason[]).map((r) => ({ value: r, label: REASON_LABEL[r] }))}
          />
          <select
            aria-label="Sort recommendations"
            value={`${lp.sortBy}:${lp.sortDir}`}
            onChange={(e) => {
              const [by, dir] = e.target.value.split(':');
              lp.setSort(by, dir as 'asc' | 'desc');
            }}
            className="h-9 rounded-md border border-line-strong bg-surface px-2.5 text-sm text-ink-700 sm:ml-auto"
          >
            {SORTS.map((s) => (
              <option key={s.value} value={s.value}>
                Sort: {s.label}
              </option>
            ))}
          </select>
        </Toolbar>

        {q.isError ? (
          <ErrorState error={q.error} onRetry={() => q.refetch()} />
        ) : q.isLoading ? (
          <ul className="divide-y divide-line">
            {Array.from({ length: 4 }).map((_, i) => (
              <li key={i} className="space-y-2 p-4">
                <Skeleton className="h-4 w-1/3" />
                <Skeleton className="h-4 w-2/3" />
              </li>
            ))}
          </ul>
        ) : !q.data?.data.length ? (
          <EmptyState title="No recommendations right now" description="Stock is balanced across facilities, or every suggestion already has an open transfer." />
        ) : (
          <ul className="divide-y divide-line">
            {q.data.data.map((r) => {
              const days = daysUntil(r.expiryDate);
              return (
                <li key={r.id} className="grid gap-4 p-4 lg:grid-cols-[minmax(0,1fr)_auto] lg:items-center">
                  <div className="min-w-0 space-y-2.5">
                    <div className="flex flex-wrap items-center gap-2">
                      <PriorityPill score={r.priorityScore} />
                      <p className="font-medium text-ink-900">
                        {r.medicine.name} <span className="font-normal text-ink-500">{r.medicine.strength}</span>
                      </p>
                      <Badge tone={r.reasonCode === 'SHORTAGE_COVER' ? 'danger' : r.reasonCode === 'NEAR_EXPIRY_SURPLUS' ? 'warning' : 'neutral'}>
                        {r.reasonCode === 'SHORTAGE_COVER' ? <TriangleAlert className="size-3" /> : <CalendarClock className="size-3" />}
                        {REASON_LABEL[r.reasonCode]}
                      </Badge>
                    </div>
                    <div className="flex flex-wrap items-center gap-x-2 gap-y-1 text-sm">
                      <span className="rounded bg-subtle px-2 py-0.5 text-ink-800">{r.sourceFacility.name}</span>
                      <ArrowRight className="size-4 text-ink-400" aria-label="to" />
                      <span className="rounded bg-brand-50 px-2 py-0.5 text-brand-700">{r.destinationFacility.name}</span>
                      <span className="flex items-center gap-1 text-xs text-ink-500">
                        <Route className="size-3.5" /> {r.distanceKm} km
                      </span>
                    </div>
                    <dl className="tabular flex flex-wrap gap-x-6 gap-y-1 text-xs text-ink-600">
                      <div>
                        <dt className="inline text-ink-500">Suggested: </dt>
                        <dd className="inline font-semibold text-ink-900">
                          {fmtNumber(r.suggestedQuantity)} {r.medicine.unit}s
                        </dd>
                      </div>
                      <div>
                        <dt className="inline text-ink-500">Batch: </dt>
                        <dd className="inline">
                          {r.batch.batchNumber} ({fmtNumber(r.batch.quantityAvailable)} avail.)
                        </dd>
                      </div>
                      <div>
                        <dt className="inline text-ink-500">Expiry: </dt>
                        <dd className={cn('inline', days <= 30 && 'font-medium text-warning-700')}>
                          {fmtDate(r.expiryDate)} ({days} d)
                        </dd>
                      </div>
                    </dl>
                    <p className="text-xs leading-relaxed text-ink-600">{r.reason}</p>
                  </div>
                  {can(user, 'transfer:request') && (
                    <Button icon={<Send className="size-3.5" />} onClick={() => accept(r)} className="justify-self-start lg:justify-self-end">
                      Request transfer
                    </Button>
                  )}
                </li>
              );
            })}
          </ul>
        )}
        <Pagination meta={q.data?.meta} onPageChange={lp.setPage} onPageSizeChange={lp.setPageSize} />
      </Card>
      <RequestTransferModal open={!!transfer} onClose={() => setTransfer(null)} prefill={transfer ?? undefined} />
    </>
  );
}
